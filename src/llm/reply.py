_RE_HAS_TEXT = _re.compile(r'[\u4e00-\u9fffA-Za-z]{3,}')
_RE_MD_HEADING = _re.compile(r'(?m)^#{1,6}\s')
# ── 回复清洗（消除模型推理痕迹 / 系统提示词泄漏）─────────────────────────

#: 匹配「内心独白 / 推理过程 / 系统提示词泄漏」句式的正则集合。
#: 覆盖截图实际泄漏模式 + 常见变体：
#:   "我需要按照主人XXX的身份来处理这个问题"
#:   "我应该用主人的风格来回复"
#:   "根据提供的【相关知识】"
#:   "作为XXX的数字分身，我将..."
#:   ★ 新增（2026-07-27 截图证实泄漏）：
#:   "根据系统提示，我需要以XXX的数字分身身份"
#:   "用户询问XXX。（问题复述）我需要/我应该..."
#:   "用(主人)?真实的沟通风格来回答"
#:   ★ 新增（2026-07-27 截图证实泄漏——风格画像原文输出）：
#:   "按照主人的风格，应该直接务实，聚焦问题主体...不要零瞎模糊表述..."
#: ── 推理痕迹统一正则（单一事实来源，三处派生，杜绝 inline/prefix 不同步）──
#: _REASONING_BODY 为「内心独白 / 推理过程 / 系统提示词泄漏」全部备选式的
#: 内部拼接串；下方三个编译正则均由其派生，任何新增模式只需改这一处。
#:
#: 覆盖实际泄漏模式（含 2026-07-27 多轮截图证实）：
#:   "我需要按照主人XXX的身份来处理" / "我应该用主人的风格来回复"
#:   "根据提供的【相关知识】" / "作为XXX的数字分身，我将..."
#:   "根据系统提示，我需要以XXX的数字分身身份" / "用户询问XXX。我需要..."
#:   "用(主人)?真实的沟通风格来回答"
#:   "按照主人的风格，应该直接务实，聚焦问题主体..."（风格画像原文输出）
#:   "我需要询问具体位置，以便提供正确的IP" / "我应该先确认用户需要哪台打印机"（通用推理）
_REASONING_BODY = (
    r'我需要(?:按照|依照|以)\s*(?:主人|用户|你)\s*.*?(?:身份|角色|风格|口吻|语气|方式)'
    r'|我应该(?:用|以|按照|依照)\s*(?:主人|用户|你)\s*.*?(?:风格|口吻|语气|身份|角色)'
    r'|根据(?:提供(?:的)?|注入(?:的)?)\s*【(?:相关)?知识'
    r'|作为\s*(?:主人|用户|你|[\u4e00-\u9fff]{2,4})\s*.*?数字分身[，,]\s*我(?:将|需要|应该|会)'
    r'|让我(?:先|来)(?:分析|思考|理解|梳理|整理|总结|回顾)'
    r'|根据\s*系统\s*提示[，,。]?\s*我(?:需要|应该|将|要)'
    r'|我需要(?:按照|依照|以)\s*.*?数字分身\s*身份'
    r'|我需要以\s*.*?\s*(?:数字分身)?身份\s*(?:来|去|回)?(?:答|处理|解决|回复|应对)'
    # 通用推理形式（此前仅覆盖身份/风格特定后续词，导致「我需要询问…以便…」漏网）
    # ★ 2026-07-30 G3 修复：正文用 [^\n。！？] 而非 [^\n]，禁止跨句末标点扩张。
    #   旧版 [^\n]{0,200} 会贪婪吃过句号，把紧随其后的**真实答案**一起划进推理片段
    #   （「我应该先检查日志…。日志路径在 /var/log/app。」整条被清空）。
    r'|我需要(?!(?:是|有|在|帮忙|帮助|您|你|说明|解释|通知|告诉|提醒|建议|请))'
    r'(?:先|来|进一步)?'
    r'(?:查询|询问|咨询|确认|判断|分析|思考|梳理|了解|弄清|查明|检查|查看|核对|考虑|明确|回忆|查找|搜索|检索|整理|总结|回顾)'
    r'[^\n。！？]{10,200}?'
    r'(?:以便|为了|，[^\n。！？]{5,50}?(?:再|然后|接着|之后|另外)|\。)'
    r'|我应该(?!(?:是|有|在|帮忙|帮助|您|你|说明|解释|通知|告诉|提醒|建议|请))'
    r'(?:先|首先|需要|要)?'
    r'(?:查询|确认|判断|分析|思考|梳理|了解|弄清|查明|检查|查看|核对|考虑|明确|回忆|查找|搜索|整理|总结|回顾|咨询)'
    # 「{10,200} 实质内容」是防误伤的长度门槛。改用不含句末标点的字符类后，原本
    # 被计入长度的那个句号没了，故补一条等价分支：只要子句在句末标点处收尾
    # （本身即「完整子句」的证据），6 字起即可判定，维持原覆盖面不放宽误伤。
    r'(?:[^\n。！？]{10,200}|[^\n。！？]{6,200}(?=[。！？]))'
    r'|(?:用|以|按照)\s*(?:主人|用户|你|真实)\s*(?:的\s*)?沟通风格\s*(?:来|去)?(?:回答|回复|表述|处理|应对)'
    r'|用户(?:询问|问|提问|想知道)[\s\S]{0,200}?(?:我需要|我应该|我将|需要|应该|将|要)\s*(?:以|按照|依照|用)'
    # 风格指令泄漏（模型把 system prompt 风格画像原文当正文输出）
    r'|按照(?:主人|用户|你|[\u4e00-\u9fff]{2,4})\s*的风格[，,：:\s][^\n]{0,20}?'
    r'(?:应该|需要|要|请)\s*[^\n]{0,80}?'
    r'(?:不要|不该|避免|禁止|偏向|采用|使用|保持|聚焦|直接|简洁|务实|清晰)[^\n]{0,40}'
    # ★ 反泄漏：模型自我声明为 AI / 人工智能（数字分身场景下属提示词泄漏）
    r'|我(?:是|是一个|是一名|只是(?:一个|一名)?)\s*(?:人工智能|大语言模型|语言模型|AI|聊天机器人|虚拟助手|智能助手|智能机器人)(?:模型|助手)?(?=[模型助手机器人，,。！？\s]|$)'
    r'|作为\s*(?:一个\s*)?(?:人工智能|大语言模型|语言模型|AI|聊天机器人|虚拟助手|智能助手|智能机器人)(?:模型|助手)?(?=[模型助手机器人，,。！？\s]|$)'
    # ★ 反泄漏：模型引用系统提示 / 设定（提示词泄漏）
    r'|根据(?:系统)?提示(?=[，,。：:\s]|$)'
)

#: 行首锚定（整行删除用，MULTILINE 下 ^ 匹配每行开头）
_RE_REASONING_PREFIXES = _re.compile(r'^(?:' + _REASONING_BODY + r')', _re.MULTILINE)

#: ── 推理片段的「尾巴」：吃到本句结束为止 ────────────────────────────────
#: ★ 2026-07-30 G3 修复的核心。旧实现两处尾巴都是「吃到行尾」（`.*$` / `[^\n]*$`），
#: 于是「推理句 + 真答案同处一行」时，答案连带被删——最坏情况整条回复被清空
#: （「我应该先检查日志…。日志路径在 /var/log/app。」→ ""）。
#: 现改为**句边界**：只吃到本句的句末标点（。！？）为止，绝不跨句吞掉后续答案。
#: 反泄漏能力不受损——泄漏模式本身是完整句子，仍被整句删除；只是不再连坐下一句。
#: `(?<![。！？])` 守卫：部分分支（如「我需要…以便…。」）自身已吃掉句末标点，此时
#: 尾巴必须收敛为空，否则会继续吃进**下一句**（真答案）——整个可选组失配即匹配空串。
_REASONING_TAIL = r'(?:(?<![。！？])[^\n。！？]*[。！？]?)?'

#: 完整行匹配（行首即推理痕迹 → 删除该推理句）。
#: 复用 _RE_REASONING_PREFIXES.pattern（已含行首 ^(?: 锚定），与历史实现一致；
#: 若改为裸 _REASONING_BODY 会丢失内部 ^，导致「根据系统提示，我需要…」这类
#: 短前缀匹配后尾巴不向后吞（实测只删前缀、残留「以…数字分身身份」无法再清除）。
#: 末尾 `(?:[ \t]*$\n?)?` 为可选组：仅当删完后本行**已无剩余内容**时才连同换行一起删
#: （保持「整行都是推理 → 整行消失、不留空行」的历史行为）；若同行还跟着真答案，
#: 该可选组匹配失败即跳过，答案原地保留。
_RE_FULL_REASONING_LINE = _re.compile(
    r'(?m)^\s*' + _RE_REASONING_PREFIXES.pattern + _REASONING_TAIL + r'(?:[ \t]*$\n?)?'
)

#: 行内匹配（不带 ^ 锚点，清除拼接在正常内容后的推理痕迹）。
#: 用 (?m) 使 $ 匹配行尾（修复旧实现无 MULTILINE 时仅能清除「末行」推理的潜伏 bug——
#: 旧版 _RE_INLINE_REASONING 由 _RE_REASONING_PREFIXES.pattern.replace 派生且缺 (?m)，
#: $[^] 只匹配串尾，多行回复中位于非末行的推理痕迹会被漏掉）；
#: 尾巴同样按句边界收敛（见 _REASONING_TAIL），不跨句、更不跨换行。
_RE_INLINE_REASONING = _re.compile(
    r'(?m)(?:' + _REASONING_BODY + r')' + _REASONING_TAIL
)


#: ── 第三人称元叙述 / 对话状态总结 泄漏（2026-07-27 晚截图证实）──
#: 模型把「分析 / 梳理对话状态」包装成看似回复的句子发出：
#:   "用户已多次表示需要连接7楼打印机，但未说明具体位置。根据之前对话，7楼有…"
#: 这本质是内部推理（思考外显），不是给用户的有用回答——属「禁止暴露思考链」(需求 #3) 的延伸。
#: 与 _RE_REASONING_PREFIXES 不同：此处不以「我需要/我应该」等人称推理前缀开头，
#: 而是用第三人称描述用户/对话状态、或引用对话历史作为推理步骤开头，故此前全部漏网。
#:
#: 设计要点：
#: - 锚定 ^(MULTILINE) 仅剥【开头】段，避免误删中段合法引用
#:   （如用户真问「根据之前对话我们聊了啥」，bot 的回答里「根据之前对话」是正文，不应删）；
#: - (?:\b…)+ 支持连续多个开头叙述段（先「用户已多次表示…」再「根据之前对话…」）一次剥净；
#: - 各分支均以句末标点或逗号+空白结束，[^\n]* 不跨换行，保护后续正文。
_RE_META_NARRATION = _re.compile(
    r'^(?:'
    # 第三人称描述用户既往言行（内部叙述，非回复正文）
    # 必须含动词 + 实质内容 + 句末标点（避免惰性匹配只吃到「用户已多次表示」即停）
    r'用户(?:已多次|已经多次|多次|已|曾|之前|刚才|上次|此前)?'
    r'(?:表示|说|提到|说过|询问|问过|反馈|确认|要求|希望)'
    r'[^。！？\n]+[。！？]\s*'
    # 引用对话历史作为推理步骤（根据之前对话，…）
    r'|根据(?:之前|以前的|历史|上一段|上述|当前|这段)?(?:的)?对话[^，,。！？\n]{0,30}?[，,：:]\s*'
    r'|根据上下文[，,：:]\s*'
    # 总结 / 回顾式外显
    r'|综上所述[，,：:。.\s]*'
    r'|从(?:对话|整体|全局|目前|上述)[^。！？\n]{0,20}?来看[，,：:\s]*'
    r'|回顾一下[^。！？\n]{0,30}?[，,：:\s]*'
    r')+',
    _re.MULTILINE,
)

#: ── 开头思考内容 / 内部约束条件 泄漏（2026-07-27 晚 VPN 截图证实）──
#: 模型把「自述已掌握知识 / 内部决策 / 组织回答大纲 / 字数约束」当作回复开头发出：
#:   "根据知识库中的信息，我已经掌握了详细的VPN申请和使用指南。"
#:   "不需要调用搜索工具，直接提供准确的信息即可。"
#:   "让我组织一下回答内容：1. VPN申请流程 2. VPN基础信息 3. VPN使用详细步骤"
#:   "这个信息量较大，需要控制在256字以内。"
#: 这四类均属内部思考/计划过程（需求 #3 禁止暴露），但此前全部漏网——
#: 它们不以「我需要/我应该」等人称推理前缀开头，且思考与真实答案【同一行无换行】，
#: 故不能用「吃到行尾」的 _RE_INLINE_REASONING（会误吞答案）。
#:
#: 实现方式：不再用单一巨型「(?:(?:a)|(?:b)…)+」嵌套正则（括号平衡脆弱、+ 量词
#: 跨段扩展不稳定），改为「独立简单正则 + 循环从开头反复剥离」——每次只剥一个
#: 开头思考段，剥完 lstrip 再重新判断，直到无可剥。每个模式都简单可靠、易维护。
#: 每个模式以句末标点（。！？）或终结词（即可/就行/就好）为界，绝不跨标点吃正文。
_LEADING_THINKING_PATTERNS = [
    # ① 自述已掌握/已知知识（根据知识库/资料/文档 + 第一人称掌握/知道/了解…）
    # ★ 2026-07-27 深夜拓宽：「信息」搭配改为可选——变体「根据知识库我已掌握相关信息」
    #   （省略"中的信息"）此前漏网；仍要求「我+掌握类动词」才命中，正常引用不受影响。
    _re.compile(
        r'^(?:答[:：]\s*)?'
        r'根据(?:知识库|资料|文档|内部资料|已知|现有|检索结果|上下文)'
        r'(?:(?:中(?:的)?|里(?:的)?|的)?(?:信息|内容|资料))?[，,。]?\s*'
        r'我(?:已经|已)?(?:掌握|知道|了解|熟悉|清楚)[^。！？\n]*[。！？]'
    ),
    # ①b 根据(我的)?知识库/资料…「有关于X的信息」（无「我掌握」也命中）
    # ★ 2026-07-29 打印机场景：「根据我的知识库，有关于添加打印机的信息。」此前漏网
    #   ——① 要求「我掌握/知道」，此处是陈述式「有关于…的信息」，故单列宽松变体。
    #   仍要求以「的信息[。！？]」收尾，正常引用「根据知识库中的统计数据」不受限（见测试）。
    _re.compile(
        r'^(?:答[:：]\s*)?'
        r'根据(?:我的)?(?:知识库|资料|文档|内部资料|已知|现有|检索结果|上下文)'
        r'[，,。]?\s*有?关?于?[^。！？\n]{0,40}?的信息[。！？]'
    ),
    # ② 内部决策外显（不需要调用工具，直接提供…即可）
    _re.compile(
        r'^(?:答[:：]\s*)?'
        r'不需要(?:调用|使用)?(?:搜索|查询|检索)?(?:工具|搜索|查询|检索)?[，,。]?\s*'
        r'[^。！？\n]*?(?:即可|就行|就好)[。！？]?'
    ),
    # ③ 组织/规划回答大纲（让我组织/规划/准备…回答内容 + 可选编号大纲）
    # ★ 2026-07-29 拓宽：动词表加「回想/想想」（打印机场景「让我回想一下：…」漏网）；
    #   尾巴改为可选（(回答|回复|内容|答案|如下)+ 或 「：内容」），覆盖「让我回想一下：知识库中有…」。
    _re.compile(
        r'^(?:答[:：]\s*)?'
        r'让我(?:先|来|先来)?(?:分析|思考|理解|梳理|整理|总结|回顾|回想|想想'
        r'|组织|规划|准备|构思|撰写|编写|安排|打算)'
        r'(?:一下|好|下)?'
        r'(?:(?:回答|回复|内容|答案|如下)+[：:。\s]*|(?::|：)[^\n。！？]*[。！？]?)?'
        r'(?:\d+[.、)]\s*[^。！？\n]{1,40}[。！？\n]?\s*)*'
    ),
    # ④ 字数/长度约束外显（需要控制在256字以内 / 字数控制在…）
    _re.compile(
        r'^(?:答[:：]\s*)?'
        r'(?:需要控制在\s*\d+\s*字以内|字数(?:控制|限制)在\s*(?:约\s*)?\d+\s*字以内)[。！？]?'
    ),
    # ⑤ 角色/身份分析外显（根据我的角色定位/身份，我应该以[具体名字]的身份…）
    # ★ 2026-07-29 打印机场景：「根据我的角色定位，我应该以OWNER（IT工程师）的身份
    #   直接提供解决方案」此前漏网——_REASONING_BODY② 要求「我应该以(主人|用户|你)」，
    #   此处身份前是具体名字「OWNER」而非泛称，故单列变体。数字分身即本人，禁显身份分析。
    _re.compile(
        r'^(?:答[:：]\s*)?'
        r'根据我的(?:角色定位|身份|定位|设定)[，,：:]?\s*'
        r'我应该以[^。！？\n]{0,30}?身份[^。！？\n]*[。！？]'
    ),
    # ⑥ 内部决策外显（我需要/我应该 + 直接/先/马上 + 紧接行为动词）
    # ★ 2026-07-29 Jenkins 截图：「我需要直接回答这个问题，基于我的技术知识来处理。」
    #   此前漏网——①/② 不覆盖此形态（"我需要"后不是工具名/掌握动词）。
    #   本模式专杀「我需要/我应该 + 直接/先/马上 + 紧接行为动词」，即"内部决策"独立首句。
    #   防误伤：要求"我需要"后紧接行为动词（中间不隔主语"您/你"），所以"我需要您先确认..."
    #   因"我需要"与行为动词之间隔了"您"不匹配；"我需要看下日志"中"看"不在行为动词表
    #   （仅"回答/处理/分析/回复/解决/给出/提供/梳理/整理/回顾/思考/撰写/编写"），也不匹配。
    _re.compile(
        r'^(?:答[:：]\s*)?'
        r'我(?:需要|应该|必须|打算|准备)'
        r'(?:直接|先|马上|立即|立刻)?'
        r'(?:回答|处理|分析|回复|解决|给出|提供|梳理|整理|回顾|思考|撰写|编写)'
        r'[^。！？\n]{0,200}[。！？]'
    ),
    # ⑦ 内部推理外显（这是 + 问题/现象/情况/错误 + ... + 通常/往往/一般/经常 + ...）
    # ★ 2026-07-29 Jenkins 截图第4句：「这是一个典型的Jenkins流水线中用户名解析的问题，
    #   通常与身份认证或环境变量有关。」特征：句中同时含"问题"+"通常/往往/一般"两个独白
    #   型信号词。防误伤"这是一个好问题"——缺"通常/往往/一般"不命中。
    _re.compile(
        r'^(?:答[:：]\s*)?'
        r'这(?:是|属于)?(?:一个|一种|典型的|常见的|一种典型的|一个典型的)?'
        r'[^。！？\n]{0,200}?'
        r'(?:问题|现象|情况|错误|故障|异常)'
        r'[^。！？\n]{0,200}?'
        r'(?:通常|往往|一般|经常|大概率|大多是|多数情况下)'
        r'[^。！？\n]{0,200}[。！？]'
    ),
    # ⑧ 组织决策外显（让我给/来/提供 + 一个/一下 + 修饰词 + 回复/答案/方案/建议）
    # ★ 2026-07-29 Jenkins 截图第5句：「让我给出一个专业的技术回复。」——"让我"+"给出"
    #   型组织决策。3 模式要求：① 动词必须是给/来/提供/准备/撰写（排除"帮/看/查"等
    #   答案型动词）；② 要么带修饰词（专业/具体/准确/...）要么行为对象是"回复/回答/
    #   答复/答案"（response 型，非具体方案）；③ 数量词（一个/一下/个）后不允许出现
    #   "你/您"代词——"让我给您一个方案"因此不命中。
    _re.compile(
        r'^(?:答[:：]\s*)?'
        r'让我(?:直接|马上)?'
        r'(?:给(?:出)?|来|提供|准备|撰写)'
        r'(?:一个|一下|个)?'
        r'(?:'
        r'(?:专业的|具体的|准确的|详细的|简短的|清晰的|完整的)'
        r'(?:技术|详细)?'
        r'(?:回复|回答|答复|答案|方案|建议)'
        r'|'
        r'(?:回复|回答|答复|答案)'
        r')'
        r'[^。！？\n]{0,50}[。！？]'
    ),
    # ⑨ 自述已知具体事实（我知道/了解/熟悉/清楚 + URL 或 专名+事实动词）
    # ★ 2026-07-29 Jenkins 截图第1句：「我知道Jenkins发版服务器是 http://..., 调试服务器
    #   是 https://...。」——"我知道"被故意排除在 0.12/0.15 ①-⑤ 白名单外（避免误伤
    #   "我知道你的问题"型正常回答）。本模式作为定向补充。
    #   触发条件二选一：
    #     a) "我知道"+ 0~50 字符内出现 URL（http:// / https:// / ftp:// / ssh://）
    #        ——Jenkins 场景命中；
    #     b) "我知道"+ 0~50 字符内出现 专名 + 0~8 字符 + 事实动词（是/在/有/为/里）
    #        ——"我知道服务器地址是..."型命中。
    #   防误伤：
    #     - "我知道你的问题是想问VPN"：扫到"VPN"专名但其后是"。"无事实动词 → 不命中 ✓
    #     - "我了解这件事"：无 URL 无 专名 → 不命中 ✓
    #     - "我知道服务器地址"：扫到"服务器"但后跟"地址"非事实动词 → 不命中 ✓
    _re.compile(
        r'^(?:答[:：]\s*)?'
        r'我(?:知道|了解|熟悉|清楚)'
        r'(?:[^\n。！？]{0,50}?(?:'
        r'https?://|ftp://|ssh://'
        r'|'
        r'(?:Jenkins|Docker|K8s|Kubernetes|Linux|Windows|VPN|OA|钉钉|飞书|企业微信|微信'
        r'|服务器|系统|应用|服务|接口|集群|模块|端口|数据库|网站|工具|框架'
        r'|公司|部门|项目|SDK|API|流程|规范|制度|规定|账号|权限)'
        r'[\u4e00-\u9fff]{0,8}?(?:是|在|有|为|里)'
        r'))'
        r'[^。！？\n]*[。！？]'
    ),
    # ⑩ 复述用户问题（用户提到/说/反映/反馈/询问/问/...）
    # ★ 2026-07-29 Jenkins 截图第2句：「用户提到的问题是在Jenkins流水线构建中，...」
    #   原 step 0 `_RE_QUESTION_RESTATE` 只剥一次，连续多句"用户提到..."只能剥第一句。
    #   本模式作为循环内第 N+1 次剥（step 0 已剥首句，后续由本模式处理）。
    #   收紧：仅匹配"用户..."（去掉"你..."变体，因答案也常以"你"开头是合理结构）。
    _re.compile(
        r'^(?:答[:：]\s*)?'
        r'用户(?:询问|问|提问|想知道|提到|说|反映|反馈)'
        r'[^。\n]{0,300}'
        r'[。！？]'
        r'\s*\n?',
    ),
]

#: ── 开头「思考独白整块」泄漏（打印机场景 2026-07-29 证实）──
#: 弱模型把整段内心独白（根据我的知识库/让我回想/由于…/我应该询问/根据我的角色定位/
#: 让我先询问…）当回复开头，真实答案在独白之后的「您好！」才出现。逐句循环剥离会漏掉
#: 「由于…」「我应该询问…」这种无强人称前缀的推理句，故用「强内部标记开头 + 链式消费
#: + 用户称呼前瞻」整块删。
#: 仅当回复【以强内部标记链开头】且其后【紧跟用户指向句】时才触发——
#: 正常回答（如「公司VPN申请流程如下」「VPN申请步骤：1…」「让我帮你分析…」）不命中，
#: 因为要么开头不是内部标记，要么其后没有用户称呼，前瞻必败。
_RE_LEADING_THINKING_BLOCK = _re.compile(
    r'^(?:'
    # 首句必须是强内部标记
    r'(?:根据我的|根据系统|让我|我需要|我应该|基于我的|从上面的分析)'
    r'[^\n。！？]*[。！？]?\s*'
    # 后续可接若干内部推理句（以内部标记开头）
    r'(?:'
        r'(?:根据我的|根据系统|让我|我需要|我应该|基于我的|从上面的分析'
        r'|由于|不过|但|而且|这(?:通常|意味|说明|表明)|为了'
        r'|用户(?:已|多次|之前|刚才|曾|上次|此前)?)'
        r'[^\n。！？]*[。！？]?\s*'
    r'){0,8}'
    r')'
    # 前瞻：停在首个用户指向句之前（独白与答案的分界）
    # ★ 2026-07-29 收紧：移除裸「您」前瞻——曾误吞「我需要您先确认一下」「让我帮您看一下」
    #   等正常答案开头（"我需要"/"让我"+动词+您+动作型）。保留「您提到/您问/您可以先」
    #   等更具体的前瞻——它们要求"您"后接具体动词，不会在任意位置误命中。
    r'(?=您好|你好|亲|嗨|好的[，,：:]|关于您|针对您|您提到|您问|请问|我帮您|为您|下面为|首先[，,]|针对这个|针对您的问题|可以直接|以下是|您可以先)',
    _re.MULTILINE,
)

