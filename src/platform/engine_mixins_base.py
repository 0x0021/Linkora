"""Platform/Engine 子系统 mixin 共享基类（F9 类型治理）。

LinkoraEngine 由 5 个顶层 mixin（Primary/Runtime/MessageLoop/Memory/Lifecycle）
经多继承组合，Runtime 又聚合 7 个运行时子 mixin。这些 mixin 交叉访问彼此的
状态（self._xxx）与方法（self._xxx()），pyright 逐文件静态分析时 self 只认
当前 mixin，故报 unknown attribute。

本类作为所有 platform mixin 的共同祖先，集中声明这些交叉成员：
- 状态：实例属性注解（无值，组合类 / 各 mixin __init__ 赋值）。内部状态统一用
  Any，因为各属性在赋值点已声明精确类型，基类用 Any 既能消解跨 mixin 访问的
  unknown-attribute 报错，又不会与赋值点的真实类型冲突。
- 方法：以「真实实现的完整签名」原样声明（非 *args/**kwargs），避免与子类
  实现的具体签名触发 reportIncompatibleMethodOverride。

惰性注解 + TYPE_CHECKING 导入，运行时零 import、零 MRO 风险。
"""
